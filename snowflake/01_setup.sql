-- 1. Create a hard cost control to avoid runaway cloud bills
CREATE OR REPLACE RESOURCE MONITOR taxi_spend_monitor
  WITH CREDIT_QUOTA = 5
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS 
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND;

-- 2. Create Warehouse with aggressive 60s auto-suspend
CREATE OR REPLACE WAREHOUSE TAXI_WH
  WITH WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  RESOURCE_MONITOR = taxi_spend_monitor;

-- 3. Database & Schemas
CREATE DATABASE IF NOT EXISTS TAXI_DB;
CREATE SCHEMA IF NOT EXISTS TAXI_DB.PROD;
CREATE SCHEMA IF NOT EXISTS TAXI_DB.STAGING;
